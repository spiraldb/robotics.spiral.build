//! Dioxus Flow projects native diagnostics into a read-only, inspectable canvas.
use crate::components::interaction::{Action, ActionPurpose, ActionVariant};
use dioxus::prelude::*;
use dioxus_flow::{
    Background, BackgroundVariant, Edge, EdgeKind, Flow, Handle, HandleKind, LayoutDirection,
    LayoutOptions, Node, NodeViewCtx, Point, Side, use_flow_handle,
};
use spiral_robotics_common::workflow::plan::{DiagnosticNode, DiagnosticPlan, SpiralPlanReport};

#[derive(Clone, Copy, PartialEq)]
enum PlanStage {
    Logical,
    Optimized,
    Physical,
}
impl PlanStage {
    fn label(self) -> &'static str {
        match self {
            Self::Logical => "Logical",
            Self::Optimized => "Optimized logical",
            Self::Physical => "Physical",
        }
    }
    fn graph(self, report: &SpiralPlanReport) -> Option<&DiagnosticPlan> {
        match self {
            Self::Logical => Some(report.logical()),
            Self::Optimized => Some(report.optimized()),
            Self::Physical => report.physical(),
        }
    }
}

#[component]
pub(super) fn NativePlanDisplay(report: SpiralPlanReport) -> Element {
    let mut stage = use_signal(|| PlanStage::Logical);
    let graph = stage().graph(&report).cloned();
    rsx! {
        div { class: "workflow-plan-display",
            div { class: "workflow-plan-controls",
                label { r#for: "workflow-plan-stage", "Plan" }
                select { id: "workflow-plan-stage", value: stage().label(),
                    onchange: move |event| stage.set(match event.value().as_str() {
                        "Physical" => PlanStage::Physical, "Optimized logical" => PlanStage::Optimized, _ => PlanStage::Logical,
                    }),
                    for option in [PlanStage::Logical, PlanStage::Optimized, PlanStage::Physical] {
                        option { value: option.label(), "{option.label()}" }
                    }
                }
                span { class: "workflow-plan-origin", "Generated by Spiral" }
            }
            if let Some(graph) = graph {
                NativePlanGraph { key: "{stage().label()}", plan: graph }
            } else {
                div { class: "workflow-panel-empty", "No physical plan is available. Inspect the logical plan and planning error." }
            }
            details { class: "workflow-plan-report", summary { "Full plan JSON" }
                pre { "{serde_json::to_string_pretty(&report).unwrap_or_default()}" }
            }
        }
    }
}

#[derive(Clone)]
struct PlanFlow {
    nodes: Vec<Node<DiagnosticNode>>,
    edges: Vec<Edge>,
}
impl From<&DiagnosticPlan> for PlanFlow {
    fn from(plan: &DiagnosticPlan) -> Self {
        let mut nodes = plan
            .nodes()
            .iter()
            .map(|node| {
                let mut displayed = Node::with_data(
                    node.id().to_string(),
                    node.operator(),
                    Point::ZERO,
                    node.clone(),
                )
                .size((224.0, 88.0))
                .sides(Side::Left, Side::Right)
                .draggable(false);
                displayed.selected = node.id() == plan.root();
                displayed
            })
            .collect::<Vec<_>>();
        let edges = plan
            .nodes()
            .iter()
            .flat_map(|node| {
                node.inputs().iter().enumerate().map(move |(index, input)| {
                    let edge = Edge::new(input.to_string(), node.id().to_string())
                        .id(format!("{}:{index}", node.id()))
                        .target_handle(format!("input-{index}"))
                        .kind(EdgeKind::SmoothStep);
                    if node.inputs().len() > 1 {
                        edge.label(format!("input {}", index + 1))
                    } else {
                        edge
                    }
                })
            })
            .collect::<Vec<_>>();
        let geometry = nodes
            .iter()
            .map(|node| dioxus_flow::LayoutNode {
                id: node.id.clone(),
                size: node.rect().size(),
            })
            .collect::<Vec<_>>();
        let connections = edges
            .iter()
            .map(|edge| (edge.source.clone(), edge.target.clone()))
            .collect::<Vec<_>>();
        let positions = dioxus_flow::compute_layout(
            &geometry,
            &connections,
            &LayoutOptions::default()
                .direction(LayoutDirection::LeftToRight)
                .gaps(32.0, 76.0),
        );
        for node in &mut nodes {
            if let Some(position) = positions.get(&node.id) {
                node.position = *position;
            }
        }
        Self { nodes, edges }
    }
}

#[component]
fn NativePlanGraph(plan: DiagnosticPlan) -> Element {
    let initial = use_hook(|| PlanFlow::from(&plan));
    let mut nodes = use_signal(|| initial.nodes);
    let edges = use_signal(|| initial.edges);
    let flow = use_flow_handle::<DiagnosticNode>();
    let selected = nodes
        .read()
        .iter()
        .find(|node| node.selected)
        .map(|node| node.data.clone());
    let root = plan.root();
    rsx! {
        div { class: "workflow-plan-graph",
            div { class: "workflow-plan-navigation",
                label { r#for: "workflow-plan-node", "Operator" }
                select { id: "workflow-plan-node", value: selected.as_ref().map(|node| node.id().to_string()).unwrap_or_default(),
                    onchange: move |event| nodes.with_mut(|nodes| {
                        for node in nodes { node.selected = node.id == event.value(); }
                    }),
                    option { value: "", disabled: true, "Select an operator" }
                    for node in plan.nodes() { option { value: "{node.id()}", "{node.operator()} · #{node.id()}" } }
                }
                span { class: "workflow-plan-count", "{plan.nodes().len()} operators" }
                Action { purpose: ActionPurpose::Fit, variant: ActionVariant::Link,
                    onclick: move |_| flow.fit_view(0), "Fit" }
                Action { purpose: ActionPurpose::Fit, variant: ActionVariant::Link,
                    title: "Zoom out", onclick: move |_| flow.zoom_out(0), "−" }
                Action { purpose: ActionPurpose::Fit, variant: ActionVariant::Link,
                    title: "Zoom in", onclick: move |_| flow.zoom_in(0), "+" }
            }
            div { class: "workflow-plan-body",
                div { class: "workflow-flow-wrap workflow-diagnostic-canvas",
                    Flow { id: "workflow-native-plan", class: "workflow-flow",
                        nodes, edges, handle: flow, fit_view: true, fit_view_padding: 0.12,
                        min_zoom: 0.1, max_zoom: 1.5, nodes_draggable: false, delete_key: false,
                        is_valid_connection: move |_| false,
                        node_view: move |ctx: NodeViewCtx<DiagnosticNode>| rsx! { PlanOperatorCard { ctx, root } },
                        Background { variant: BackgroundVariant::Dots, gap: 24.0, size: 0.6 }
                    }
                }
                aside { class: "workflow-plan-inspector", "aria-label": "Plan operator details",
                    if let Some(node) = &selected { PlanOperatorDetails { node: node.clone() } }
                    else { p { "Select an operator to inspect its schema and properties." } }
                }
            }
        }
    }
}

#[component]
fn PlanOperatorCard(ctx: NodeViewCtx<DiagnosticNode>, root: u64) -> Element {
    let node = &ctx.node.data;
    let schema = node.output().get("schema");
    let dtype = schema
        .and_then(|schema| schema.get("dtype"))
        .and_then(serde_json::Value::as_str)
        .unwrap_or("Schema in details");
    rsx! {
        div { class: if ctx.node.selected { "workflow-plan-operator is-selected" } else { "workflow-plan-operator" },
            div { class: "workflow-plan-operator-heading", strong { "{node.operator()}" } span { "#{node.id()}" } }
            code { title: dtype, "{dtype}" }
            small { if node.id() == root { "Query output" } else if node.inputs().is_empty() { "Source" } else if node.inputs().len() == 1 { "1 input" } else { "{node.inputs().len()} inputs" } }
            for (index, _) in node.inputs().iter().enumerate() {
                Handle { id: format!("input-{index}"), kind: HandleKind::Target, position: Side::Left,
                    offset: (index + 1) as f64 / (node.inputs().len() + 1) as f64 }
            }
            if node.id() != root { Handle { kind: HandleKind::Source, position: Side::Right } }
        }
    }
}

#[component]
fn PlanOperatorDetails(node: DiagnosticNode) -> Element {
    let fields = node
        .output()
        .pointer("/schema/fields")
        .and_then(serde_json::Value::as_array);
    rsx! {
        h3 { "{node.operator()}" }
        p { class: "workflow-plan-node-id", "Operator #{node.id()}" }
        h4 { "Output schema" }
        if let Some(fields) = fields.filter(|fields| !fields.is_empty()) {
            table { class: "workflow-plan-schema", thead { tr { th { "Column" } th { "Type" } th { "Nullable" } } }
                tbody { for field in fields {
                    { let name = field["name"].as_str().unwrap_or_default();
                      let dtype = field["dtype"].as_str().unwrap_or_default();
                      rsx! { tr { td { "{name}" } td { "{dtype}" }
                          td { if field["nullable"].as_bool() == Some(true) { "Yes" } else { "No" } }
                      } }
                    }
                } }
            }
        } else { p { "No named output columns." } }
        h4 { "Properties" }
        pre { "{serde_json::to_string_pretty(node.properties()).unwrap_or_default()}" }
        if let Some(details) = node.details() { h4 { "Operator details" } pre { "{details}" } }
        details { summary { "Full output metadata" } pre { "{serde_json::to_string_pretty(node.output()).unwrap_or_default()}" } }
        if let Some(execution) = node.execution() {
            details { summary { "Execution identity" } pre { "{serde_json::to_string_pretty(execution).unwrap_or_default()}" } }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    #[wasm_bindgen_test::wasm_bindgen_test]
    fn flow_preserves_shared_inputs_and_native_nodes_without_editing_the_plan() {
        let plan: DiagnosticPlan =
            serde_json::from_value(json!({"schema_version":1,"root":0,"nodes":[
                {"id":0,"operator":"Union","inputs":[1,1],"output":{},"properties":{}},
                {"id":1,"operator":"Values","inputs":[],"output":{},"properties":{}}
            ]}))
            .unwrap();
        let original = plan.clone();
        let flow = PlanFlow::from(&plan);
        assert_eq!(flow.nodes.len(), 2);
        assert_eq!(flow.edges.len(), 2);
        assert_ne!(flow.edges[0].id, flow.edges[1].id);
        assert_ne!(flow.edges[0].target_handle, flow.edges[1].target_handle);
        assert_eq!(flow.edges[0].source, "1");
        assert_eq!(flow.edges[0].target, "0");
        assert!(flow.nodes.iter().all(|node| !node.draggable));
        assert!(flow.nodes[1].position.x < flow.nodes[0].position.x);
        assert_eq!(plan, original);
    }
}
